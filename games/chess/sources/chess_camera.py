"""One Blender camera profile shared by the board plate and piece atlases."""
import json
from pathlib import Path

TABLE_TOP = 2.1
BOARD_Y = 2.4
PLAYABLE_SIDE = 9.4
BOARD_SURFACE_Z = TABLE_TOP + 0.325
PIECE_BASE_Z = TABLE_TOP + 0.345
CAMERA_TARGET = (0.0, BOARD_Y, TABLE_TOP + 0.2475)
CAMERA_LOCATION = (0.0, BOARD_Y - 15.0, CAMERA_TARGET[2] + 29.7)
CAMERA_LENS = 92.0
SENSOR_WIDTH = 36.0
BOARD_RESOLUTION = (1800, 1600)
PIECE_FRAME_WORLD_WIDTH = 2.8


def camera_basis():
    """Return the fixed Blender camera's forward, right and up unit vectors."""
    from mathutils import Vector

    forward = (Vector(CAMERA_TARGET) - Vector(CAMERA_LOCATION)).normalized()
    right = forward.cross(Vector((0.0, 0.0, 1.0))).normalized()
    up = right.cross(forward).normalized()
    return forward, right, up


def piece_camera_location(position):
    """Translate the fixed camera so one piece base sits on its optical axis."""
    from mathutils import Vector

    point = Vector(position)
    camera = Vector(CAMERA_LOCATION)
    forward, _, _ = camera_basis()
    depth = (point - camera).dot(forward)
    return point - forward * depth, depth


def profile():
    width, height = BOARD_RESOLUTION
    return {
        "camera_position": list(CAMERA_LOCATION),
        "camera_target": list(CAMERA_TARGET),
        "lens": CAMERA_LENS,
        "sensor_width": SENSOR_WIDTH,
        "sensor_height": SENSOR_WIDTH * height / width,
        "board_center": [0.0, BOARD_Y],
        "playable_side": PLAYABLE_SIDE,
        "board_surface_z": BOARD_SURFACE_Z,
        "piece_base_z": PIECE_BASE_Z,
        "image_width": width,
        "image_height": height,
    }


def write_profile(path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(profile(), indent=2) + "\n")


def write_godot_profile(path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join(
        f'\t"{key}": {json.dumps(value)}' for key, value in profile().items()
    )
    path.write_text(
        "# Generated by sources/chess_camera.py; rerun `npm run blender -- chess board-table`.\n"
        "extends RefCounted\n\n"
        f"const PROFILE: Dictionary = {{\n{body}\n}}\n"
    )
